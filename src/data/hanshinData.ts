export function generate16WeekSyllabus(course: Course): WeekProgress[] {
  // If we already have pre-configured syllabus for course-sw201, use it
  if (course.id === 'course-sw201' && INITIAL_WEEK_PROGRESS['course-sw201']) {
    return INITIAL_WEEK_PROGRESS['course-sw201'];
  }

  const startDate = new Date('2026-03-03');
  const weeks: WeekProgress[] = [];

  for (let w = 1; w <= 16; w++) {
    const classDate = new Date(startDate);
    classDate.setDate(startDate.getDate() + (w - 1) * 7);
    const dateStr = classDate.toISOString().split('T')[0];

    const isMidterm = w === 8;
    const isFinal = w === 16;

    let title = `${w}주차: ${course.name} ${w}주차 강의`;
    let topic = `${course.name} 핵심 이론 및 실습`;
    let format: any = '이론강의';
    let status: any = w === 1 ? '진행중' : '예정';

    if (isMidterm) {
      title = '8주차: [중간고사 평가] 필기 및 실기 테스트';
      topic = '1주차~7주차 전 범위 평가';
      format = '시험평가';
    } else if (isFinal) {
      title = '16주차: [기말고사 평가] 및 학기 종강';
      topic = '학기 전 범위 최종 평가';
      format = '시험평가';
    } else if (w % 3 === 0) {
      format = '실습실습';
    }

    weeks.push({
      weekNumber: w,
      title,
      topic,
      objectives: [
        `${w}주차 핵심 개념의 이해 및 이론 습득`,
        `실무 응용 과제 수행 및 문제 해결 능력 함양`,
      ],
      format,
      status,
      scheduledDate: dateStr,
      materials: `강의자료 ${String(w).padStart(2, '0')}장`,
      tasks: [
        { id: `task-${w}-1`, text: `${w}주차 강의 슬라이드 및 실습 예제 검토`, done: false },
        { id: `task-${w}-2`, text: '학생 질의응답 및 피드백 점검', done: false },
      ],
      lectureNotes: '',
      attendancePresent: 0,
      attendanceTotal: course.enrolledStudents || 40,
    });
  }

  return weeks;
}
